/** 归一化单个标签；未知标签保留原样 */
export function normKnowledge(k: string): string {
  const s = String(k || '').trim();
  if (!s) return '';
  return KNOWLEDGE_ALIAS[s] || s;
}

/** 归一化标签列表并去重 */
export function normKnowledgeList(list: readonly string[]): string[] {
  const out: string[] = [];
  (list || []).forEach((k) => {
    const c = normKnowledge(k);
    if (c && !out.includes(c)) out.push(c);
  });
  return out;
}

/** 标签 → 一级域；未收录的归入「其他」 */
export function domainOf(k: string): string {
  return KNOWLEDGE_DOMAIN[k] || '其他';
}

/** 从来源标题提取届次，用于按届聚合（如「2024 第十六届…」→「第十六届」） */
export function sourceGroup(src: string): string {
  const m = String(src || '').match(/第[一二三四五六七八九十]+届/);
  return m ? m[0] : src || '未分类';
}
